export interface PendingTable {
  id: string
  name: string
  rowCount: number
  columnCount: number
  table: Table
  data: DatasetData
}

export interface PendingImport {
  tables: PendingTable[]
  relationships: number
  fileNames: string[]
  currentTables: number
  currentMeasures: number
  isSampleData: boolean
  templateName: string | null
}

/** Run the auto-model engine over the current datasets + tables. */
function analyze(
  datasets: DatasetData[],
  tables: Table[],
): { tables: Table[]; relationships: Relationship[] } {
  const inputs = datasets
    .map((data) => {
      const table = tables.find((t) => t.id === data.id)
      return table ? { data, table } : null
    })
    .filter((x): x is { data: DatasetData; table: Table } => x !== null)
  if (inputs.length === 0) return { tables, relationships: [] }
  const res = buildModel(inputs)
  return { tables: res.tables, relationships: res.relationships }
}

/** Generate measures + an auto-dashboard from a model; attach measures to tables. */
function buildArtifacts(model: SemanticModel): { model: SemanticModel; report: Report } {
  const { page, measures } = generateDashboard(model)
  const tables = model.tables.map((t) => {
    const measuresForTable: Measure[] = measures
      .filter((m) => m.tableId === t.id)
      .map((m) => ({
        id: m.id,
        name: m.name,
        expression: m.dax.includes(' = ') ? m.dax.split(' = ').slice(1).join(' = ') : m.dax,
        formatString: m.formatString,
        displayFolder: m.displayFolder,
        description: `Auto-generated ${m.kind} measure`,
        confidence: m.confidence,
        isAutoGenerated: true,
      }))
    return { ...t, measures: measuresForTable }
  })
  const report: Report = {
    id: 'report',
    name: 'Report',
    pages: [page],
    activePageId: page.id,
    themeId: 'studio',
  }
  return { model: { ...model, tables }, report }
}


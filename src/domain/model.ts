/**
 * DOMAIN — Semantic Model
 * Pure, framework-free entities describing a tabular model. These serialize
 * losslessly to TMDL/PBIP on export.
 */

export type Id = string

/** Storage/semantic type of a column. */
export type DataType =
  | 'string'
  | 'integer'
  | 'decimal'
  | 'boolean'
  | 'date'
  | 'dateTime'
  | 'time'

/** Inferred business role of a column, produced by the Auto-Model engine. */
export type ColumnRole =
  | 'key' // primary/foreign key candidate
  | 'measureCandidate' // additive numeric fact
  | 'dimension' // descriptive attribute
  | 'date' // temporal
  | 'geography' // country/region/city/lat-long
  | 'flag' // boolean / status
  | 'unknown'

/** Inferred role of a table. */
export type TableRole = 'fact' | 'dimension' | 'date' | 'bridge' | 'unknown'

export type Cardinality = 'one' | 'many'

export interface Column {
  id: Id
  name: string
  dataType: DataType
  role: ColumnRole
  /** Distinct value count / row count — drives fact/dim + visual decisions. */
  cardinalityRatio?: number
  distinctCount?: number
  nullCount?: number
  sampleValues?: unknown[]
  formatString?: string
  isHidden?: boolean
  displayFolder?: string
}

export interface Measure {
  id: Id
  name: string
  /** DAX expression. */
  expression: string
  formatString?: string
  displayFolder?: string
  description?: string
  /** Confidence from the KPI engine when auto-generated (0..1). */
  confidence?: number
  isAutoGenerated?: boolean
}

export interface Table {
  id: Id
  name: string
  role: TableRole
  columns: Column[]
  measures: Measure[]
  rowCount?: number
  /** Source reference (file, query, connector). */
  source?: { kind: string; ref: string }
  isHidden?: boolean
}

export interface Relationship {
  id: Id
  fromTable: Id
  fromColumn: Id
  toTable: Id
  toColumn: Id
  fromCardinality: Cardinality
  toCardinality: Cardinality
  isActive: boolean
  crossFilter: 'single' | 'both'
  /** Auto-model confidence (0..1). */
  confidence?: number
}

export interface SemanticModel {
  id: Id
  name: string
  tables: Table[]
  relationships: Relationship[]
  culture?: string
}

export const emptyModel = (id: Id, name: string): SemanticModel => ({
  id,
  name,
  tables: [],
  relationships: [],
  culture: 'en-US',
})

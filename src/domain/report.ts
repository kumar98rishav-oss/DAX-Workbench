/**
 * DOMAIN — Report tree
 * Pages contain visuals laid out on a canvas grid. Serializes to the PBIP
 * report definition on export.
 */
import type { Id } from './model'

export type VisualKind =
  | 'card'
  | 'kpi'
  | 'multiRowCard'
  | 'line'
  | 'area'
  | 'bar'
  | 'column'
  | 'stackedBar'
  | 'combo'
  | 'pie'
  | 'donut'
  | 'funnel'
  | 'gauge'
  | 'waterfall'
  | 'treemap'
  | 'scatter'
  | 'table'
  | 'matrix'
  | 'map'
  | 'slicer'
  | 'text'

/** A field binding on a visual (measure or column reference). */
export interface FieldBinding {
  table: Id
  field: Id
  role: 'category' | 'value' | 'series' | 'axis' | 'tooltip' | 'legend'
  aggregation?: 'sum' | 'avg' | 'min' | 'max' | 'count' | 'distinctCount'
}

export interface Rect {
  x: number
  y: number
  w: number
  h: number
}

export interface Visual {
  id: Id
  kind: VisualKind
  title?: string
  rect: Rect
  bindings: FieldBinding[]
  /** Free-form visual-level style overrides. */
  style?: Record<string, unknown>
  /** Provenance when produced by the recommendation engine. */
  isAutoGenerated?: boolean
}

export interface Page {
  id: Id
  name: string
  visuals: Visual[]
  /** Logical design size; the canvas scales responsively. */
  width: number
  height: number
  background?: string
}

export interface Report {
  id: Id
  name: string
  pages: Page[]
  activePageId: Id | null
  themeId?: string
}

export const emptyReport = (id: Id, name: string): Report => ({
  id,
  name,
  pages: [],
  activePageId: null,
})

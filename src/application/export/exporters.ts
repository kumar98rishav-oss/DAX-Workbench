// ---------------------------------------------------------------------------
// PBIP file set (bundled into a ZIP)
// ---------------------------------------------------------------------------

export function buildPBIP(model: SemanticModel, report: Report, name: string): ZipEntry[] {
  const safe = name.replace(/[^A-Za-z0-9_-]+/g, '_') || 'project'
  const entries: ZipEntry[] = []

  entries.push({
    path: `${safe}.pbip`,
    content: JSON.stringify(
      { version: '1.0', artifacts: [{ report: { path: `${safe}.Report` } }], settings: { enableAutoRecovery: true } },
      null,
      2,
    ),
  })

  // Semantic model (TMDL)
  entries.push({
    path: `${safe}.SemanticModel/definition/model.tmdl`,
    content: `model Model\n\tculture: en-US\n\ndefaultPowerBIDataSourceVersion: powerBI_V3\n`,
  })
  for (const t of model.tables) {
    entries.push({ path: `${safe}.SemanticModel/definition/tables/${t.name}.tmdl`, content: tableToTMDL(model, t.id) })
  }
  entries.push({ path: `${safe}.SemanticModel/definition/relationships.tmdl`, content: relationshipsTMDL(model) })
  entries.push({
    path: `${safe}.SemanticModel/definition.pbism`,
    content: JSON.stringify({ version: '4.0', settings: {} }, null, 2),
  })

  // Report
  entries.push({ path: `${safe}.Report/report.json`, content: toProjectJSON(model, report) })
  entries.push({ path: `${safe}.Report/definition.pbir`, content: JSON.stringify({ version: '1.0', datasetReference: { byPath: { path: `../${safe}.SemanticModel` } } }, null, 2) })

  // Docs + theme
  entries.push({ path: `${safe}.Report/StaticResources/theme.json`, content: toThemeJSON() })
  entries.push({ path: `README.md`, content: toMarkdown(model, report) })

  return entries
}

// ---- helpers ----
const q = (name: string): string => (/[^A-Za-z0-9_]/.test(name) ? `'${name}'` : name)

const TMDL_TYPE: Record<DataType, string> = {
  string: 'string',
  integer: 'int64',
  decimal: 'double',
  boolean: 'boolean',
  date: 'dateTime',
  dateTime: 'dateTime',
  time: 'dateTime',
}

function fmtNum(v: number, kind: MeasureKind): string {
  if (kind === 'ratio') return `${(v * 100).toFixed(1)}%`
  const a = Math.abs(v)
  const s = a >= 1e9 ? `${(v / 1e9).toFixed(1)}B` : a >= 1e6 ? `${(v / 1e6).toFixed(1)}M` : a >= 1e3 ? `${(v / 1e3).toFixed(1)}K` : `${Math.round(v)}`
  return kind === 'currency' ? `$${s}` : s
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

// ---------------------------------------------------------------------------
// TMDL
// ---------------------------------------------------------------------------

export function tableToTMDL(model: SemanticModel, tableId: string): string {
  const t = model.tables.find((x) => x.id === tableId)
  if (!t) return ''
  const lines: string[] = [`table ${q(t.name)}`, '']
  for (const c of t.columns) {
    lines.push(`\tcolumn ${q(c.name)}`)
    lines.push(`\t\tdataType: ${TMDL_TYPE[c.dataType]}`)
    lines.push(`\t\tsummarizeBy: ${c.role === 'measureCandidate' ? 'sum' : 'none'}`)
    lines.push(`\t\tsourceColumn: ${c.name}`)
    if (c.isHidden) lines.push(`\t\tisHidden`)
    lines.push('')
  }
  for (const m of t.measures) {
    lines.push(`\tmeasure ${q(m.name)} = ${m.expression.replace(/\n/g, '\n\t\t')}`)
    if (m.formatString) lines.push(`\t\tformatString: ${m.formatString}`)
    if (m.displayFolder) lines.push(`\t\tdisplayFolder: ${m.displayFolder}`)
    lines.push('')
  }
  return lines.join('\n')
}

export function relationshipsTMDL(model: SemanticModel): string {
  const out: string[] = []
  model.relationships.forEach((r, i) => {
    const from = model.tables.find((t) => t.id === r.fromTable)
    const to = model.tables.find((t) => t.id === r.toTable)
    const fromCol = from?.columns.find((c) => c.id === r.fromColumn)
    const toCol = to?.columns.find((c) => c.id === r.toColumn)
    if (!from || !to || !fromCol || !toCol) return
    out.push(`relationship rel_${i + 1}`)
    out.push(`\tfromColumn: ${q(from.name)}.${q(fromCol.name)}`)
    out.push(`\ttoColumn: ${q(to.name)}.${q(toCol.name)}`)
    if (!r.isActive) out.push(`\tisActive: false`)
    if (r.crossFilter === 'both') out.push(`\tcrossFilteringBehavior: bothDirections`)
    out.push('')
  })
  return out.join('\n')
}

export function toTMDL(model: SemanticModel): string {
  const parts = [`// Model: ${model.name}`, `// Generated by BI Design Studio`, '']
  for (const t of model.tables) parts.push(tableToTMDL(model, t.id), '')
  parts.push(relationshipsTMDL(model))
  return parts.join('\n')
}

// ---------------------------------------------------------------------------
// Markdown documentation
// ---------------------------------------------------------------------------

export function toMarkdown(model: SemanticModel, report: Report): string {
  const md: string[] = [`# ${model.name} — Model Documentation`, '', `_Generated by BI Design Studio._`, '']
  md.push(`## Overview`, '')
  md.push(`- **Tables:** ${model.tables.length}`)
  md.push(`- **Relationships:** ${model.relationships.length}`)
  md.push(`- **Measures:** ${model.tables.reduce((n, t) => n + t.measures.length, 0)}`)
  md.push(`- **Report pages:** ${report.pages.length}`, '')

  for (const t of model.tables) {
    md.push(`## ${t.name} \`${t.role}\``, '')
    md.push(`| Column | Type | Role | Distinct |`, `| --- | --- | --- | --- |`)
    for (const c of t.columns) {
      md.push(`| ${c.name} | ${c.dataType} | ${c.role} | ${c.distinctCount ?? '—'} |`)
    }
    md.push('')
    if (t.measures.length) {
      md.push(`**Measures**`, '')
      for (const m of t.measures) md.push(`- \`${m.name}\` = \`${m.expression.replace(/\n/g, ' ')}\``)
      md.push('')
    }
  }

  if (model.relationships.length) {
    md.push(`## Relationships`, '')
    model.relationships.forEach((r) => {
      const from = model.tables.find((t) => t.id === r.fromTable)
      const to = model.tables.find((t) => t.id === r.toTable)
      const fc = from?.columns.find((c) => c.id === r.fromColumn)
      const tc = to?.columns.find((c) => c.id === r.toColumn)
      if (from && to && fc && tc) md.push(`- ${from.name}[${fc.name}] → ${to.name}[${tc.name}] (${r.fromCardinality}:${r.toCardinality})`)
    })
    md.push('')
  }
  return md.join('\n')
}


// ---------------------------------------------------------------------------
// Tabular Editor C# script
// ---------------------------------------------------------------------------

export function toTabularEditorScript(model: SemanticModel): string {
  const lines: string[] = ['// Tabular Editor C# script — recreates measures', '// Generated by BI Design Studio', '']
  for (const t of model.tables) {
    for (const m of t.measures) {
      const expr = m.expression.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, ' ')
      lines.push(`try {`)
      lines.push(`    var m = Model.Tables["${t.name}"].AddMeasure("${m.name}", "${expr}");`)
      if (m.formatString) lines.push(`    m.FormatString = "${m.formatString.replace(/\\/g, '\\\\')}";`)
      if (m.displayFolder) lines.push(`    m.DisplayFolder = "${m.displayFolder}";`)
      lines.push(`} catch (Exception ex) { Info(ex.Message); }`)
      lines.push('')
    }
  }
  return lines.join('\n')
}


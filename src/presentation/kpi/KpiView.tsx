import { useEffect, useMemo, useRef, useState } from 'react'
import { Gauge, Grid3X3, Table2, MonitorX, Loader2, ZoomIn, ZoomOut, Scan } from 'lucide-react'
import { useApp } from '@/app/store'
import { makeCtx } from '@/application/query/query-engine'
import { evaluateDax } from '@/application/dax/evaluator'
import { modelMeasures, defineHomeTable } from '@/application/dax/live-preview'
import {
  buildKpiBoardQuery,
  buildAnswerQuery,
  mapAnswerRows,
  pivotMatrix,
  formatValue,
} from '@/application/dax/answers'
import type { DimRef } from '@/application/dax/answers'
import { desktopRunDax } from '@/infrastructure/desktop/desktop-client'
import './kpi.css'

const SLOTS = 12
const ROW_CAP = 500
const MATRIX_CAP = 2000

type Page = 'board' | 'matrix' | 'table'

interface MeasureInfo {
  id: string
  name: string
  dax: string
  formatString?: string
  tableName: string
  isAutoGenerated?: boolean
}

/** The KPI surface: measures you create become live answers — a 12-card board,
 * a matrix, and a table, all computed by the real engine when connected. */
export function KpiView() {
  const model = useApp((s) => s.model)
  const datasets = useApp((s) => s.datasets)
  const desktop = useApp((s) => s.desktop)
  const kpiOverrides = useApp((s) => s.kpiOverrides)
  const setKpiSlot = useApp((s) => s.setKpiSlot)
  const matrixCfg = useApp((s) => s.answersMatrix)
  const setMatrix = useApp((s) => s.setAnswersMatrix)
  const tableCfg = useApp((s) => s.answersTable)
  const setTable = useApp((s) => s.setAnswersTable)
  const inspectMeasure = useApp((s) => s.inspectMeasure)
  const selectedMeasureId = useApp((s) => s.selectedMeasureId)
  const zoom = useApp((s) => s.kpiZoom)
  const setZoom = useApp((s) => s.setKpiZoom)

  const [page, setPage] = useState<Page>('board')
  const scrollRef = useRef<HTMLDivElement>(null)
  const zoomRef = useRef<HTMLDivElement>(null)

  /** Pick the zoom that makes the current page's content just fit the pane. */
  const fitToScreen = () => {
    const c = scrollRef.current
    const w = zoomRef.current
    if (!c || !w) return
    c.scrollTop = 0
    const natural = w.getBoundingClientRect().height / zoom
    const avail = c.getBoundingClientRect().bottom - w.getBoundingClientRect().top - 36
    if (natural > 0 && avail > 100) setZoom(avail / natural)
  }

  const all: MeasureInfo[] = useMemo(
    () =>
      model.tables.flatMap((t) =>
        t.measures.map((m) => ({
          id: m.id,
          name: m.name,
          dax: m.expression,
          formatString: m.formatString,
          tableName: t.name,
          isAutoGenerated: m.isAutoGenerated,
        })),
      ),
    [model],
  )
  const byName = useMemo(() => new Map(all.map((m) => [m.name, m])), [all])
  const home = useMemo(() => defineHomeTable(model), [model])
  const ctx = useMemo(() => makeCtx(model, datasets), [model, datasets])

  // Auto-fill: newest first (measures append as they're created), hand-written
  // before auto-generated. Overrides pin or clear individual slots.
  const slots: (string | null)[] = useMemo(() => {
    const user = all.filter((m) => !m.isAutoGenerated).reverse()
    const auto = all.filter((m) => m.isAutoGenerated).reverse()
    const pool = [...user, ...auto].map((m) => m.name)
    const taken = new Set(
      Object.values(kpiOverrides).filter((v): v is string => typeof v === 'string'),
    )
    const queue = pool.filter((n) => !taken.has(n))
    return Array.from({ length: SLOTS }, (_, i) => {
      if (i in kpiOverrides) return kpiOverrides[i]
      return queue.shift() ?? null
    })
  }, [all, kpiOverrides])

  // ---- live values for the board: ONE engine query for every filled slot ----
  const [liveVals, setLiveVals] = useState<Record<string, unknown>>({})
  const [boardBusy, setBoardBusy] = useState(false)
  const slotKey = slots.filter(Boolean).join('')
  useEffect(() => {
    setLiveVals({})
    const picked = slots.filter((n): n is string => n !== null && byName.has(n))
    if (!desktop.connected || !home || picked.length === 0) return
    const t = setTimeout(() => {
      setBoardBusy(true)
      desktopRunDax(buildKpiBoardQuery(modelMeasures(model), picked, home), desktop.port)
        .then((r) => {
          const row = r.rows[0] ?? {}
          const vals: Record<string, unknown> = {}
          picked.forEach((name, i) => { vals[name] = row[r.columns[i]] })
          setLiveVals(vals)
        })
        .catch(() => { /* cards fall back to sample values */ })
        .finally(() => setBoardBusy(false))
    }, 400)
    return () => clearTimeout(t)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [slotKey, desktop.connected, desktop.port, model])

  const sampleValue = (m: MeasureInfo): string => {
    const r = evaluateDax(m.dax, ctx)
    return r.ok ? formatValue(r.value, m.formatString) : '—'
  }

  // ---- matrix + table answers, engine-only ----
  const [answer, setAnswer] = useState<{
    for: string
    columns: string[]
    rows: Record<string, unknown>[]
  } | null>(null)
  const [answerBusy, setAnswerBusy] = useState(false)
  const [answerErr, setAnswerErr] = useState<string | null>(null)

  const dimOptions = useMemo(
    () =>
      model.tables.flatMap((t) =>
        t.columns.map((c) => ({ key: `${t.name}|${c.name}`, label: `${t.name}[${c.name}]` })),
      ),
    [model],
  )
  const parseDim = (key: string): DimRef => {
    const [table, column] = key.split('|')
    return { table, column }
  }

  const activeCfgKey =
    page === 'matrix'
      ? `m:${matrixCfg.row}:${matrixCfg.col}:${matrixCfg.values.join(',')}`
      : `t:${tableCfg.dims.join(',')}:${tableCfg.values.join(',')}`

  useEffect(() => {
    if (page === 'board') return
    setAnswerErr(null)
    const dims: DimRef[] =
      page === 'matrix'
        ? ([matrixCfg.row, matrixCfg.col].filter(Boolean) as string[]).map(parseDim)
        : tableCfg.dims.map(parseDim)
    const values = (page === 'matrix' ? matrixCfg.values : tableCfg.values).filter((v) => byName.has(v))
    if (!desktop.connected || !home || dims.length === 0 || values.length === 0) {
      setAnswer(null)
      return
    }
    const t = setTimeout(() => {
      setAnswerBusy(true)
      const cap = page === 'matrix' ? MATRIX_CAP : ROW_CAP
      desktopRunDax(buildAnswerQuery(dims, values, modelMeasures(model), home, cap), desktop.port)
        .then((r) => setAnswer({ for: activeCfgKey, columns: r.columns, rows: r.rows }))
        .catch((e) => { setAnswer(null); setAnswerErr(e instanceof Error ? e.message : 'Query failed') })
        .finally(() => setAnswerBusy(false))
    }, 400)
    return () => clearTimeout(t)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [page, activeCfgKey, desktop.connected, desktop.port, model])

  const fmtFor = (name: string): string | undefined => byName.get(name)?.formatString

  // ---------------------------------------------------------------- render
  return (
    <div className="kpiview pbs-scroll" ref={scrollRef}>
      <div className="kpiview__head">
        <div className="kpiview__tabs">
          <button className="kpiview__tab" data-on={page === 'board'} onClick={() => setPage('board')}>
            <Gauge size={14} /> KPI Board
          </button>
          <button className="kpiview__tab" data-on={page === 'matrix'} onClick={() => setPage('matrix')}>
            <Grid3X3 size={14} /> Matrix
          </button>
          <button className="kpiview__tab" data-on={page === 'table'} onClick={() => setPage('table')}>
            <Table2 size={14} /> Table
          </button>
        </div>
        {desktop.connected ? (
          <span className="dax-badge dax-badge--live">live · full data</span>
        ) : (
          <span className="dax-badge dax-badge--sample">sample — connect Desktop for live</span>
        )}
        {(boardBusy || answerBusy) && <Loader2 size={14} className="pbs-spin kpiview__busy" />}

        <div className="kpiview__zoomctl">
          <button className="kpiview__zoombtn" title="Zoom out" onClick={() => setZoom(zoom - 0.1)}>
            <ZoomOut size={14} />
          </button>
          <button className="kpiview__zoompct" title="Reset to 100%" onClick={() => setZoom(1)}>
            {Math.round(zoom * 100)}%
          </button>
          <button className="kpiview__zoombtn" title="Zoom in" onClick={() => setZoom(zoom + 0.1)}>
            <ZoomIn size={14} />
          </button>
          <button className="kpiview__zoombtn kpiview__zoomfit" title="Fit to screen" onClick={fitToScreen}>
            <Scan size={14} /> Fit
          </button>
        </div>
      </div>

      <div className="kpiview__zoom" ref={zoomRef} style={{ zoom }}>
      {page === 'board' && (
        <div className="kpi-grid">
          {slots.map((name, i) => {
            const m = name ? byName.get(name) : undefined
            const live = m && liveVals[m.name] !== undefined
            return (
              <div
                key={i}
                className="kpi-card"
                data-empty={!m}
                data-clickable={!!m}
                data-sel={!!m && selectedMeasureId === m.id}
                title={m ? 'Click to open this measure in the DAX tab below' : undefined}
                onClick={() => m && inspectMeasure(m.id)}
              >
                <select
                  className="kpi-card__pick"
                  value={m?.name ?? ''}
                  onClick={(e) => e.stopPropagation()}
                  onChange={(e) => setKpiSlot(i, e.target.value || null)}
                >
                  <option value="">— empty —</option>
                  {all.map((x) => (
                    <option key={x.name} value={x.name}>{x.name}</option>
                  ))}
                </select>
                {m ? (
                  <>
                    <div className="kpi-card__value">
                      {live ? formatValue(liveVals[m.name], m.formatString) : sampleValue(m)}
                    </div>
                    <div className="kpi-card__foot">
                      <span className="kpi-card__table">{m.tableName}</span>
                      <em className={`dax-badge ${live ? 'dax-badge--live' : desktop.connected ? 'dax-badge--sample' : 'dax-badge--local'}`}>
                        {live ? 'live' : desktop.connected ? '…' : 'sample'}
                      </em>
                    </div>
                  </>
                ) : (
                  <div className="kpi-card__empty">Pick a measure — new ones fill in automatically</div>
                )}
              </div>
            )
          })}
        </div>
      )}

      {page !== 'board' && (
        <div className="ans">
          <div className="ans__config">
            {page === 'matrix' ? (
              <>
                <label className="dax-field">
                  <span className="dax-field__label">Rows</span>
                  <select className="dax-select" value={matrixCfg.row ?? ''} onChange={(e) => setMatrix({ row: e.target.value || null })}>
                    <option value="">— choose —</option>
                    {dimOptions.map((d) => <option key={d.key} value={d.key}>{d.label}</option>)}
                  </select>
                </label>
                <label className="dax-field">
                  <span className="dax-field__label">Columns (optional)</span>
                  <select className="dax-select" value={matrixCfg.col ?? ''} onChange={(e) => setMatrix({ col: e.target.value || null })}>
                    <option value="">— none —</option>
                    {dimOptions.map((d) => <option key={d.key} value={d.key}>{d.label}</option>)}
                  </select>
                </label>
              </>
            ) : (
              <label className="dax-field">
                <span className="dax-field__label">Columns from tables</span>
                <select
                  className="dax-select"
                  value=""
                  onChange={(e) => { if (e.target.value && !tableCfg.dims.includes(e.target.value)) setTable({ dims: [...tableCfg.dims, e.target.value] }) }}
                >
                  <option value="">+ add a column…</option>
                  {dimOptions.map((d) => <option key={d.key} value={d.key}>{d.label}</option>)}
                </select>
                <div className="ans__chips">
                  {tableCfg.dims.map((d) => (
                    <button key={d} className="ans__chip" onClick={() => setTable({ dims: tableCfg.dims.filter((x) => x !== d) })} title="Remove">
                      {parseDim(d).table}[{parseDim(d).column}] ✕
                    </button>
                  ))}
                </div>
              </label>
            )}

            <div className="dax-field">
              <span className="dax-field__label">Measures {page === 'matrix' && matrixCfg.col ? '(first is shown when Columns is set)' : ''}</span>
              <div className="ans__measures pbs-scroll">
                {all.map((m) => {
                  const list = page === 'matrix' ? matrixCfg.values : tableCfg.values
                  const on = list.includes(m.name)
                  const toggle = () => {
                    const next = on ? list.filter((x) => x !== m.name) : [...list, m.name]
                    if (page === 'matrix') setMatrix({ values: next })
                    else setTable({ values: next })
                  }
                  return (
                    <label key={m.name} className="ans__measure" data-on={on}>
                      <input type="checkbox" checked={on} onChange={toggle} /> {m.name}
                    </label>
                  )
                })}
              </div>
            </div>
          </div>

          <div className="ans__result">
            {!desktop.connected ? (
              <div className="ans__note"><MonitorX size={15} /> Matrix and Table run on the real engine — connect Power BI Desktop to get answers.</div>
            ) : answerErr ? (
              <div className="ans__note ans__note--err">{answerErr}</div>
            ) : !answer || answer.for !== activeCfgKey ? (
              <div className="ans__note">
                {answerBusy ? 'Asking the engine…' : page === 'matrix' ? 'Pick Rows and at least one measure.' : 'Add a column and at least one measure.'}
              </div>
            ) : page === 'matrix' && matrixCfg.col ? (
              (() => {
                const flat = mapAnswerRows(answer.columns, answer.rows, 2)
                const pv = pivotMatrix(flat)
                const measureName = matrixCfg.values[0]
                return (
                  <div className="ans__scroll pbs-scroll">
                    <table className="ans__tbl">
                      <thead>
                        <tr>
                          <th>{parseDim(matrixCfg.row!).column}</th>
                          {pv.colKeys.map((c) => <th key={c}>{c}</th>)}
                        </tr>
                      </thead>
                      <tbody>
                        {pv.rows.map((r) => (
                          <tr key={r.key}>
                            <td className="ans__dim">{r.key}</td>
                            {pv.colKeys.map((_, ci) => (
                              <td key={ci} className="ans__num">{formatValue(r.cells[ci], fmtFor(measureName))}</td>
                            ))}
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )
              })()
            ) : (
              (() => {
                const dims = page === 'matrix' ? [matrixCfg.row!].map(parseDim) : tableCfg.dims.map(parseDim)
                const values = page === 'matrix' ? matrixCfg.values : tableCfg.values
                const flat = mapAnswerRows(answer.columns, answer.rows, dims.length)
                return (
                  <div className="ans__scroll pbs-scroll">
                    <table className="ans__tbl">
                      <thead>
                        <tr>
                          {dims.map((d) => <th key={d.column}>{d.column}</th>)}
                          {values.map((v) => <th key={v} className="ans__num">{v}</th>)}
                        </tr>
                      </thead>
                      <tbody>
                        {flat.map((r, i) => (
                          <tr key={i}>
                            {r.dims.map((d, j) => <td key={j} className="ans__dim">{String(d ?? '(blank)')}</td>)}
                            {r.values.map((v, j) => <td key={j} className="ans__num">{formatValue(v, fmtFor(values[j]))}</td>)}
                          </tr>
                        ))}
                      </tbody>
                    </table>
                    {answer.rows.length >= (page === 'matrix' ? MATRIX_CAP : ROW_CAP) && (
                      <div className="ans__cap">Showing the first {page === 'matrix' ? MATRIX_CAP : ROW_CAP} rows.</div>
                    )}
                  </div>
                )
              })()
            )}
          </div>
        </div>
      )}
      </div>
    </div>
  )
}
